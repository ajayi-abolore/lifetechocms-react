
import fs from 'node:fs';
import path from 'node:path';

import {
  discoverReactFiles,
  getRelativeName,
  getEntryName
} from './GenerateEntries.js';

export function generateLayoutHtml({
  outputDirectory,
  projectRoot,
  viewsDirectory = 'src/Views',
  layouts = {},
  themeName
}) {
  const manifestPath = path.join(
    outputDirectory,
    '.vite',
    'manifest.json'
  );

  if (!fs.existsSync(manifestPath)) {
    throw new Error(
      'LifeTechOCMS: Vite manifest not found.'
    );
  }

  const manifest = JSON.parse(
    fs.readFileSync(manifestPath, 'utf8')
  );

  const layoutsOutput = path.join(
    outputDirectory,
    'Layouts'
  );

  const viewsOutput = path.join(
    outputDirectory,
    'Views'
  );

  fs.mkdirSync(layoutsOutput, { recursive: true });
  fs.mkdirSync(viewsOutput, { recursive: true });

  // Find the generated entry in the Vite manifest.
  function findEntry(entryName) {
    const expectedFile = `Assets/js/${entryName}.js`;

    const match = Object.entries(manifest).find(
      ([, entry]) =>
        entry.isEntry &&
        entry.file === expectedFile
    );

    if (!match) {
      throw new Error(
        `LifeTechOCMS: Missing Vite entry: ${entryName}`
      );
    }

    const [key, entry] = match;

    return { key, entry };
  }

  // Collect CSS from an entry and its imported chunks.
  function collectCss(entryKey) {
    const cssFiles = new Set();
    const visited = new Set();

    function visit(key) {
      if (visited.has(key)) return;
      visited.add(key);

      const chunk = manifest[key];
      if (!chunk) return;

      for (const css of chunk.css ?? []) {
        cssFiles.add(css);
      }

      for (const imported of chunk.imports ?? []) {
        visit(imported);
      }
    }

    visit(entryKey);

    return [...cssFiles];
  }

  // Resolve a generated asset using LifeTechOCMS.
  const assetUrl = file =>
    `<?= ltThemePath() ?>/${themeName}/${file.replace(/\\/g, '/')}`;

  function generateImports(entryKey, entry) {
    const cssImports = collectCss(entryKey)
      .map(file =>
        `<link rel="stylesheet" href="${assetUrl(file)}">`
      )
      .join('\n');

    const jsImport =
      `<script type="module" src="${assetUrl(entry.file)}"></script>`;

    return { cssImports, jsImport };
  }

  // Write an HTML file, preserving nested directories.
  function writeHtml(root, relativeName, html) {
    const destination = path.join(
      root,
      ...relativeName.split('/').slice(0, -1),
      `${relativeName.split('/').at(-1)}.html`
    );

    fs.mkdirSync(
      path.dirname(destination),
      { recursive: true }
    );

    fs.writeFileSync(destination, html, 'utf8');

    return destination;
  }

  // Generate Layout HTML resources.
  for (const layoutName of Object.keys(layouts).sort()) {
    const entryName = getEntryName(
      'Layout',
      layoutName
    );

    const { key, entry } = findEntry(entryName);

    const { cssImports, jsImport } =
      generateImports(key, entry);

    const html = [
      '<!-- Generated by @lifetechocms/react -->',
      '',
      '<div id="lt-react-layout"></div>',
      '',
      '<div id="lt-dynamic-content" hidden>',
      '    <?php dddm::loadDynamicContent(); ?>',
      '</div>',
      '',
      cssImports,
      jsImport,
      ''
    ].join('\n');

    writeHtml(layoutsOutput, layoutName, html);

    console.log(
      `[LifeTechOCMS] Generated Layout: ${layoutName}.html`
    );
  }

  // Generate View HTML resources.
  const sourceViews = path.resolve(
    projectRoot,
    viewsDirectory
  );

  if (!fs.existsSync(sourceViews)) {
    throw new Error(
      `LifeTechOCMS: Views directory not found: ${sourceViews}`
    );
  }

  if (!fs.statSync(sourceViews).isDirectory()) {
    throw new Error(
      `LifeTechOCMS: Expected a Views directory: ${sourceViews}`
    );
  }
  const viewFiles = discoverReactFiles(sourceViews);

  for (const file of viewFiles) {
    const viewName = getRelativeName(
      sourceViews,
      file
    );

    const entryName = getEntryName(
      'View',
      viewName
    );

    const { key, entry } = findEntry(entryName);

    const { cssImports, jsImport } =
      generateImports(key, entry);

    const html = [
      '<!-- Generated by @lifetechocms/react -->',
      '',
      `<div data-lt-view="${viewName}"></div>`,
      '',
      cssImports,
      jsImport,
      ''
    ].join('\n');

    writeHtml(viewsOutput, viewName, html);

    console.log(
      `[LifeTechOCMS] Generated View: ${viewName}.html`
    );
  }
}
